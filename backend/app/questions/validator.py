"""Grounding and structure validation for LLM-written questions.

A draft is accepted only if its evidence can be found in the retrieved context and its
answer is consistent with its type. Rejected drafts are regenerated by the caller.
"""

from __future__ import annotations

import hashlib
import random
import re
from dataclasses import dataclass

from app.ingestion.models import Chunk
from app.questions.models import BLANK, QuestionDraft, QuestionType
from app.text_utils import content_tokens, normalize_answer, token_overlap

MIN_QUESTION_CHARS = 10
MIN_EVIDENCE_OVERLAP = 0.85  # fraction of evidence tokens that must appear in one context chunk
MIN_ANSWER_GROUNDING = 0.5  # fraction of free-form answer tokens that must appear in the context
MIN_BLANK_ANSWER_OVERLAP = 0.8
MCQ_OPTION_RANGE = (3, 5)
MAX_KEY_POINTS = 5
_BLANK_RE = re.compile(r"_{3,}|\[blank\]|\(blank\)", re.IGNORECASE)
_TRUE_WORDS = {"true", "t", "yes", "correct"}
_FALSE_WORDS = {"false", "f", "no", "incorrect"}


class DraftRejected(Exception):
    def __init__(self, problems: list[str]) -> None:
        super().__init__("; ".join(problems))
        self.problems = problems


@dataclass(frozen=True)
class ValidatedDraft:
    question: str
    answer: str
    options: list[str]
    acceptable_answers: list[str]
    key_points: list[str]
    explanation: str
    evidence: str
    source_chunks: list[Chunk]


def parse_bool(text: str) -> bool | None:
    normalized = normalize_answer(text)
    if normalized in _TRUE_WORDS:
        return True
    if normalized in _FALSE_WORDS:
        return False
    return None


def find_evidence_chunks(evidence: str, context: list[Chunk]) -> list[Chunk]:
    """Chunks that contain the evidence verbatim (normalised) or nearly so."""
    target = normalize_answer(evidence)
    if not target or len(content_tokens(evidence)) < 2:
        return []
    return [
        c
        for c in context
        if target in normalize_answer(c.text) or token_overlap(evidence, c.text) >= MIN_EVIDENCE_OVERLAP
    ]


def _deterministic_shuffle(options: list[str], key: str) -> list[str]:
    """Shuffle options so the correct answer is not always first (LLMs have position bias)."""
    shuffled = list(options)
    random.Random(int(hashlib.sha1(key.encode()).hexdigest()[:8], 16)).shuffle(shuffled)
    return shuffled


class DraftValidator:
    def validate(self, draft: QuestionDraft, question_type: QuestionType, context: list[Chunk]) -> ValidatedDraft:
        problems: list[str] = []
        question = draft.question.strip()
        if len(question) < MIN_QUESTION_CHARS:
            problems.append("question text is missing or too short")
        if not draft.explanation.strip():
            problems.append("explanation is missing")

        evidence_chunks = find_evidence_chunks(draft.evidence_quote, context)
        if not evidence_chunks:
            problems.append("evidence_quote was not found in the provided context")
        cited = [c for c in context if c.chunk_id in set(draft.source_chunk_ids)]
        sources = list({c.chunk_id: c for c in evidence_chunks + cited}.values())
        context_text = " ".join(c.text for c in context)

        answer, options = draft.answer.strip(), [o.strip() for o in draft.options if o.strip()]
        if not answer:
            problems.append("answer is missing")
        elif question_type == QuestionType.MULTIPLE_CHOICE:
            answer, options = self._check_mcq(answer, options, question, problems)
        elif question_type == QuestionType.TRUE_FALSE:
            answer = self._check_true_false(answer, problems)
        elif question_type == QuestionType.FILL_IN_BLANK:
            question = self._check_fill_in_blank(question, answer, draft.evidence_quote, problems)
        else:
            self._check_free_form(draft, answer, context_text, question_type, problems)

        if problems:
            raise DraftRejected(problems)
        return ValidatedDraft(
            question=question,
            answer=answer,
            options=options,
            acceptable_answers=[a.strip() for a in draft.acceptable_answers if a.strip()],
            key_points=[k.strip() for k in draft.key_points if k.strip()][:MAX_KEY_POINTS],
            explanation=draft.explanation.strip(),
            evidence=draft.evidence_quote.strip(),
            source_chunks=sources,
        )

    @staticmethod
    def _check_mcq(answer: str, options: list[str], question: str, problems: list[str]) -> tuple[str, list[str]]:
        low, high = MCQ_OPTION_RANGE
        if not low <= len(options) <= high:
            problems.append(f"multiple choice needs {low}-{high} options, got {len(options)}")
            return answer, options
        normalized = [normalize_answer(o) for o in options]
        if len(set(normalized)) != len(options):
            problems.append("options are not distinct")
        letter = answer.strip().upper().rstrip(").")
        if len(letter) == 1 and "A" <= letter < chr(ord("A") + len(options)):
            answer = options[ord(letter) - ord("A")]  # recover from a letter answer
        matches = [o for o, n in zip(options, normalized) if n == normalize_answer(answer)]
        if len(matches) != 1:
            problems.append("answer does not match exactly one option")
            return answer, options
        return matches[0], _deterministic_shuffle(options, question)

    @staticmethod
    def _check_true_false(answer: str, problems: list[str]) -> str:
        value = parse_bool(answer)
        if value is None:
            problems.append("true/false answer must be 'true' or 'false'")
            return answer
        return "True" if value else "False"

    @staticmethod
    def _check_fill_in_blank(question: str, answer: str, evidence: str, problems: list[str]) -> str:
        if not _BLANK_RE.search(question):
            problems.append("fill-in-the-blank question has no blank (_____)")
            return question
        question = _BLANK_RE.sub(BLANK, question)
        if token_overlap(answer, evidence) < MIN_BLANK_ANSWER_OVERLAP and normalize_answer(answer) not in normalize_answer(evidence):
            problems.append("blank answer does not appear in the evidence")
        if normalize_answer(answer) and normalize_answer(answer) in normalize_answer(question):
            problems.append("question reveals the blank's answer")
        return question

    @staticmethod
    def _check_free_form(
        draft: QuestionDraft, answer: str, context_text: str, question_type: QuestionType, problems: list[str]
    ) -> None:
        if not [k for k in draft.key_points if k.strip()]:
            problems.append("key_points are required for free-form questions")
        if question_type == QuestionType.CALCULATION:
            if not re.search(r"\d", answer) or not re.search(r"\d", draft.evidence_quote):
                problems.append("calculation needs numbers in both the answer and the evidence")
            return  # the computed result need not appear verbatim in the text
        if content_tokens(answer) and token_overlap(answer, context_text) < MIN_ANSWER_GROUNDING:
            problems.append("model answer is not supported by the context")
